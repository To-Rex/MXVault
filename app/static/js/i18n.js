/* Global translation function */
function t(key, lang) {
  lang = lang || (window.__mxvault_lang || 'uz');
  const dict = i18n[lang] || i18n['en'];
  return dict[key] || key;
}

/* Shared Alpine.js lang component */
document.addEventListener('alpine:init', () => {
  Alpine.data('langData', () => ({
    lang: 'uz',

    init() {
      const saved = this.getCookie('mxvault_lang');
      if (saved && i18n[saved]) this.lang = saved;
      window.__mxvault_lang = this.lang;
      this.$nextTick(() => this.applyLang());
    },

    setLang(l) {
      this.lang = l;
      window.__mxvault_lang = l;
      this.setCookie('mxvault_lang', l, 365);
      this.$nextTick(() => this.applyLang());
    },

    applyLang() {
      document.documentElement.lang = this.lang === 'uz' ? 'uz' : this.lang === 'ru' ? 'ru' : 'en';
      document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.dataset.i18n;
        const dict = i18n[this.lang] || i18n['uz'];
        if (dict[key]) el.textContent = dict[key];
      });
    },

    getCookie(name) {
      const match = document.cookie.match(new RegExp('(^| )' + name + '=([^;]+)'));
      return match ? match[2] : null;
    },

    setCookie(name, value, days) {
      const d = new Date();
      d.setTime(d.getTime() + days * 86400000);
      document.cookie = name + '=' + value + ';path=/;expires=' + d.toUTCString() + ';SameSite=Lax';
    }
  }));
});

/* Observe dynamic content for new [data-i18n] elements */
if (typeof MutationObserver !== 'undefined') {
  const i18nObserver = new MutationObserver(() => {
    const lang = window.__mxvault_lang || 'uz';
    const dict = i18n[lang] || i18n['uz'];
    document.querySelectorAll('[data-i18n]:not([data-i18n-done])').forEach(el => {
      const key = el.dataset.i18n;
      if (dict[key]) {
        el.textContent = dict[key];
        el.dataset.i18nDone = '1';
      }
    });
  });
  document.addEventListener('DOMContentLoaded', () => {
    i18nObserver.observe(document.body, { childList: true, subtree: true });
  });
}
